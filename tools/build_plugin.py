#!/usr/bin/env python3
"""Bundle src/ayarci/*.py + ui.html into the single file OrcaSlicer installs: dist/ayarci.py

Usage:  python tools/build_plugin.py [--author "Name"] [--repo https://github.com/you/ayarci]
"""
import argparse
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "ayarci")
ORDER = ["catalog", "rules", "safety", "geometry", "prompt", "providers", "i18n", "assist", "ui", "plugin"]

HEADER = '''# /// script
# requires-python = ">=3.12"
# dependencies = ["numpy", "certifi", "anthropic"]
#
# [tool.orcaslicer.plugin]
# id = "ayarci"
# name = "3DsetuPia – AI Print Settings Assistant"
# description = "Looks at the model on the plate and tunes quality, strength, speed, support and filament settings for it, with your approval. Works with any AI (Claude, OpenAI, Gemini, Ollama...) or offline with built-in rules."
# author = "{author}"
# version = "{version}"
# type = "script"
# ///
"""3DsetuPia – AI print-settings assistant for OrcaSlicer.

Copyright (C) {year} {author}.
This program is free software: you can redistribute it and/or modify it under the terms of
the GNU Affero General Public License as published by the Free Software Foundation, either
version 3 of the License, or (at your option) any later version. See LICENSE.

Source code, issues and documentation: {repo}

THIS FILE IS GENERATED by tools/build_plugin.py from src/ayarci/. Edit the sources, not this file.
"""
'''


def strip_module(name, text):
    out = []
    lines = text.splitlines()
    # drop the module docstring (kept in the sources)
    tree = ast.parse(text)
    skip_until = 0
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], "value", None), ast.Constant) \
            and isinstance(tree.body[0].value.value, str):
        skip_until = tree.body[0].end_lineno
    for i, line in enumerate(lines, start=1):
        if i <= skip_until:
            continue
        if line.rstrip().endswith("# bundle:strip"):
            continue
        out.append(line)
    body = "\n".join(out).strip("\n")
    if re.search(r"^\s*from \.", body, re.M) or re.search(r"^\s*import ayarci", body, re.M):
        raise SystemExit("relative import left in %s.py; mark it with '# bundle:strip'" % name)
    return "# " + "=" * 70 + "\n# module: %s\n# " % name + "=" * 70 + "\n" + body + "\n"


def _owner():
    path = os.path.join(ROOT, "tools", "owner.txt")
    out = {}
    if os.path.isfile(path):
        for line in open(path, encoding="utf-8"):
            if "=" in line:
                k, v = line.strip().split("=", 1)
                out[k] = v
    return out


def main():
    owner = _owner()
    default_repo = "https://github.com/%s/3DsetuPia" % owner.get("github", "Keanyy")
    ap = argparse.ArgumentParser()
    ap.add_argument("--author", default=os.environ.get("AYARCI_AUTHOR", owner.get("author", "3DsetuPia contributors")))
    ap.add_argument("--repo", default=os.environ.get("AYARCI_REPO", default_repo))
    ap.add_argument("--out", default=os.path.join(ROOT, "dist", "ayarci.py"))
    args = ap.parse_args()

    plugin_src = open(os.path.join(SRC, "plugin.py"), encoding="utf-8").read()
    version = re.search(r'PLUGIN_VERSION = "([^"]+)"', plugin_src).group(1)
    import datetime
    parts = [HEADER.format(author=args.author, version=version, repo=args.repo,
                           year=datetime.date.today().year)]
    for name in ORDER:
        if name == "ui":
            html = open(os.path.join(SRC, "ui.html"), encoding="utf-8").read()
            parts.append("# " + "=" * 70 + "\n# module: ui (generated from ui.html)\n# " + "=" * 70 +
                         "\nUI_HTML = " + repr(html) + "\n")
            continue
        text = open(os.path.join(SRC, name + ".py"), encoding="utf-8").read()
        if name == "plugin":
            text = re.sub(r'REPO_URL = "[^"]*"', 'REPO_URL = "%s"' % args.repo, text)
        parts.append(strip_module(name, text))
    bundle = "\n\n".join(parts)
    compile(bundle, "ayarci.py", "exec")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(bundle)
    print("wrote %s (%d KB, version %s)" % (args.out, len(bundle.encode()) // 1024, version))


if __name__ == "__main__":
    sys.exit(main())
